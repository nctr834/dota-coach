"""Build RAG_content_heroes.json without API calls.
Reads pos_data.json for position info, uses hardcoded guide text.
Run: python scripts/build_hero_guides.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

with open(ROOT / "data/pos_data.json") as f:
    pos_data = json.load(f)
with open(ROOT / "data/hero_data.json") as f:
    _hero_data = json.load(f)
name_to_id = {h["displayName"]: hid for hid, h in _hero_data.items()}

POS_NAMES = {
    "1": "Carry (Pos 1)",
    "2": "Mid (Pos 2)",
    "3": "Offlane (Pos 3)",
    "4": "Soft Support (Pos 4)",
    "5": "Hard Support (Pos 5)",
}


def get_positions(hero_id):
    positions = []
    for pos_key, heroes in pos_data.items():
        entry = heroes.get(str(hero_id))
        if entry and entry["matchCount"] >= 50:
            wr = (
                round(entry["winCount"] / entry["matchCount"] * 100, 1)
                if entry["matchCount"] > 0
                else 0
            )
            positions.append(
                (
                    pos_key,
                    POS_NAMES.get(pos_key, f"Pos {pos_key}"),
                    wr,
                    entry["matchCount"],
                )
            )
    positions.sort(key=lambda x: x[3], reverse=True)
    return positions



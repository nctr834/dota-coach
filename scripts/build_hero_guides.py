def build():
    output = {}
    for name, hero_id in sorted(name_to_id.items()):
        guide = GUIDES.get(name)
        if not guide:
            print(f"  SKIP {name}: no guide data")
            continue

        goal, requires, fights, dont, timings, gameStage = guide
        positions = get_positions(hero_id)
        if positions:
            pos_str = positions[0][1]
            pos_nums = [int(p[0]) for p in positions[:2]]
        else:
            pos_str = "Unknown"
            pos_nums = []

        output[name] = {
            "id": hero_id,
            "position": pos_str,
            "positionNumber": pos_nums,
            "goal": goal,
            "requires": requires,
            "fights": fights,
            "dont": dont,
            "timings": timings,
            "gameStage": gameStage,
        }

    out_path = ROOT / "data/RAG/RAG_content_heroes.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(output, f, indent=2)
    print(f"Wrote {len(output)} hero guides to {out_path}")


if __name__ == "__main__":
    build()
